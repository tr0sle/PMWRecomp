"""Writes runtime/stubs.c: a fatal-error stub for every imported function that the
runtime does not implement yet, plus the import lookup table used by GetProcAddress."""
import os, re, glob
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
defined = set()
for fn in glob.glob(os.path.join(ROOT, "runtime", "*.c")):
    if fn.endswith("stubs.c"):
        continue
    src = open(fn, encoding="utf-8").read()
    for dll, name in re.findall(r"^HLE\((\w+),\s*(\w+)\)", src, re.M):
        defined.add("hle_%s_%s" % (dll, name))
imports = re.findall(r'\{0x[0-9a-f]+,"([^"]+)","([^"]+)",(\w+)\}', open(os.path.join(ROOT, "gen", "disp.c")).read())
out = ['/* generated by tools/gen_stubs.py */', '#include "hle.h"', '']
seen = set()
missing = []
for dll, name, fn in imports:
    if fn in defined or fn in seen:
        continue
    seen.add(fn)
    missing.append(fn)
    out.append('void %s(void) { fatal("unimplemented import %s!%s"); }' % (fn, dll, name))
out.append('')
open(os.path.join(ROOT, "runtime", "stubs.c"), "w").write("\n".join(out))
print("stubs:", len(missing), " ".join(missing))
